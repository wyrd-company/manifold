//   implements: host-command-catalog
// ---
import { readFile, readdir, writeFile } from "node:fs/promises";
import { parse } from "yaml";
import { mergeCommandTrees } from "../src/catalog/merge.ts";

const directory = new URL("../../../docs/specifications/", import.meta.url);
const names = (await readdir(directory))
  .filter((name) => /^host-cli.*\.cli\.yml$/.test(name))
  .sort();
const ordered = ["host-cli.cli.yml", ...names.filter((name) => name !== "host-cli.cli.yml")];
const assets = await Promise.all(
  ordered.map(async (name) => parse(await readFile(new URL(name, directory), "utf8"))),
);
const tree = mergeCommandTrees(assets);
function runnable(nodes, prefix = []) {
  return nodes.flatMap((node) =>
    node.subcommands
      ? runnable(node.subcommands, [...prefix, node.name])
      : [[...prefix, node.name].join(" ")],
  );
}
const text = `// ---\n// relationships:\n//   implements: host-command-catalog\n// ---\n// Generated by scripts/generate-command-tree.mjs.\nexport const commandTree = ${JSON.stringify(tree, null, 2)} as const;\nexport type RunnablePath = ${runnable(
  tree.commands,
)
  .map((path) => JSON.stringify(path))
  .join(" | ")};\n`;
await writeFile(new URL("../src/catalog/command-tree.generated.ts", import.meta.url), text);
