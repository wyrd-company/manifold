import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import ts from "typescript";

const require = createRequire(import.meta.url);
const directory = dirname(require.resolve("typescript"));
const names = new Set();
function visit(name) {
  if (names.has(name)) return;
  names.add(name);
  for (const reference of ts.preProcessFile(readFileSync(join(directory, name), "utf8"))
    .libReferenceDirectives)
    visit(`lib.${reference.fileName}.d.ts`);
}
visit("lib.es2022.d.ts");
const ordered = [...names].sort();
const output = [
  "// ---\n// relationships:\n//   implements: host-cli-comparator-lint\n// ---",
  "// Generated by scripts/generate-comparator-library.mjs.",
  'import type { ComparatorLintLibrary } from "./index.ts";',
  "// @ts-expect-error Bun imports declaration files as text; TypeScript treats them as declarations.",
  'import contract from "@wyrd-company/manifold-shared/comparator.d.ts" with { type: "text" };',
  ...ordered.flatMap((name, index) => [
    "// @ts-expect-error Bun imports declaration files as text; TypeScript treats them as declarations.",
    `import lib${index} from "typescript/lib/${name}" with { type: "text" };`,
  ]),
  "export const comparatorLintLibrary: ComparatorLintLibrary = {",
  "  contract,",
  "  libFiles: new Map([",
  ...ordered.map((name, index) => `    ["${name}", lib${index}],`),
  "  ]),",
  "};",
  "",
].join("\n");
writeFileSync(new URL("../src/comparator-lint/library.generated.ts", import.meta.url), output);
