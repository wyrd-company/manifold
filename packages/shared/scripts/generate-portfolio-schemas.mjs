import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const definitions = ["portfolio", "bindings"].map((name) => {
  const asset = new URL(
    `../../../docs/specifications/${name}-declaration.schema.yml`,
    import.meta.url,
  );
  const constant =
    name === "portfolio" ? "portfolioDeclarationSchema" : "bindingsDeclarationSchema";
  return `export const ${constant} = ${JSON.stringify(parse(readFileSync(asset, "utf8")), null, 2)};`;
});
writeFileSync(
  new URL("../src/portfolio-declaration-schema.ts", import.meta.url),
  `// ---\n// relationships:\n//   implements: [portfolio-declaration, bindings-declaration]\n// ---\n// Generated by scripts/generate-portfolio-schemas.mjs.\n${definitions.join("\n\n")}\n`,
);
