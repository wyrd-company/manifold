import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { parse } from "yaml";
import { Ajv2020 } from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
const schema = parse(
  readFileSync(
    new URL("../../../docs/specifications/decision-models.schema.yml", import.meta.url),
    "utf8",
  ),
);
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
ajv.addSchema(schema);
const source = standalone(ajv, {
  validateModel: schema.$id + "#/$defs/decision-model",
  validateEvaluation: schema.$id + "#/$defs/decision-model-evaluation",
}).replace(
  /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\).default;/g,
  "const $1 = value => [...value].length;",
);
writeFileSync(
  new URL("../src/decision-model-validators.js", import.meta.url),
  `// ---\n// relationships:\n//   realizes: decision-models\n// ---\n/* eslint-disable */\n// Schema digest: ${createHash("sha256").update(JSON.stringify(schema)).digest("hex")}\n// Generated by scripts/generate-decision-model-validators.mjs; agreement is tested.\n${source}`,
);
